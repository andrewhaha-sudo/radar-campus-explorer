#!/usr/bin/env python3
"""Carry the real v1 (els911-portal) data into the v2 (pathfinder) schema.

Reads the verified pre-migration backup rather than the live v1 database, so the
migration is reproducible and cannot be affected by concurrent v1 edits:

    ~/backups/els911-mapping-2026-08-18/v1.db

v1 is flat (users -> projects -> documents) and v2 is hierarchical
(orgs -> districts -> facilities -> buildings -> projects -> documents), so the
hierarchy is synthesised:

    org        the existing ELS911 org in v2
    district   from v1 projects.district, deduplicated; projects with no
               district hang directly off the org
    facility   one per v1 project - a school IS a facility
    building   one "Main" per facility; v1 had no building concept
    project    the v1 project record, now under its building
    documents  carried over verbatim, ids and R2 storage keys preserved

The interesting part is FLOORS. v1 had no floor concept: floors were separate
PDFs related only by filename convention, and re-surveys were distinguished by a
"Final" suffix. FLOOR_PLAN below encodes that inference explicitly, per project,
so it is reviewable rather than hidden in a regex. Anything not listed gets a
single floor named "Main".

Version currency rule: when several documents map to one floor, the one that
CARRIES MARKERS is current - that is where the annotation work actually lives.

Emits SQL on stdout. Every statement is INSERT OR IGNORE against a deterministic
id, so re-running is safe and converges.
"""

import os
import re
import sqlite3
import sys
import uuid

BACKUP = os.path.expanduser("~/backups/els911-mapping-2026-08-18/v1.db")
ORG_ID = "org-els911-0000-0000-0000-000000000001"

# Floor stacks inferred from filenames, lowest floor first. Each entry is
# (floor_label, [document filename fragments, oldest version first]).
# Reviewed against the actual document list in the backup README.
FLOOR_PLAN = {
    "Rock L. Butler": [
        ("0", ["RockButlerFloor0"]),
        ("Main", ["RockButlerMainFloor"]),
        ("3", ["RockButlerFloor3Final"]),
    ],
    "South Williamsport Elementary": [
        ("1", ["S_Will_Ele_-_Floor_1"]),
        ("2", ["S_Will_Ele_-_Floor_2"]),
    ],
    "Charlotte Lapla": [
        ("Main", ["Charlotte_Lappla", "CharlotteLapplaFinal"]),
    ],
}


# v1 allowed statuses v2's CHECK does not. An unmapped value would be silently
# dropped by INSERT OR IGNORE, taking the project's documents, markers and
# annotations with it - the same failure mode as the v1 room-marker CHECK bug.
STATUS_MAP = {
    "pending": "draft",
    "draft": "draft",
    "in_review": "in_review",
    "approved": "approved",
    "archived": "archived",
    "complete": "approved",
    "completed": "approved",
}
V2_STATUSES = {"draft", "in_review", "approved", "archived"}


def map_status(v1_status):
    mapped = STATUS_MAP.get((v1_status or "").strip().lower(), "draft")
    if mapped not in V2_STATUSES:
        raise SystemExit(f"unmapped project status: {v1_status!r}")
    return mapped


def det_id(prefix: str, *parts: str) -> str:
    """Deterministic uuid5 so re-running the migration converges."""
    seed = "|".join(parts)
    return f"{prefix}-{uuid.uuid5(uuid.NAMESPACE_URL, seed)}"


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main() -> int:
    if not os.path.exists(BACKUP):
        print(f"backup not found: {BACKUP}", file=sys.stderr)
        return 1

    db = sqlite3.connect(BACKUP)
    db.row_factory = sqlite3.Row
    out = []
    w = out.append

    w("-- Generated by scripts/migrate-v1-data.py. Idempotent: deterministic ids")
    w("-- + INSERT OR IGNORE throughout, so re-running converges.")
    w("")

    # --- users -------------------------------------------------------------
    # v1 emails (els911.com / gmail / proton) do not collide with the v2 seed
    # users (@test.com), so all six carry over with their original ids.
    w("-- users")
    for u in db.execute("SELECT * FROM users"):
        w(
            "INSERT OR IGNORE INTO users (id,name,email,password_hash,salt,role,org,active,created_at) VALUES "
            f"({q(u['id'])},{q(u['name'])},{q(u['email'])},{q(u['password_hash'])},{q(u['salt'])},"
            f"{q(u['role'])},{q('ELS911')},{q(u['active'] if u['active'] is not None else 1)},{q(u['created_at'])});"
        )
    w("")

    fallback_user = db.execute(
        "SELECT id FROM users WHERE role='admin' ORDER BY created_at LIMIT 1"
    ).fetchone()["id"]

    projects = list(db.execute("SELECT * FROM projects ORDER BY name"))

    # --- districts ---------------------------------------------------------
    w("-- districts (deduplicated from v1 projects.district)")
    districts = {}
    for p in projects:
        name = (p["district"] or "").strip()
        if not name or name in districts:
            continue
        did = det_id("dist", "els911", name)
        districts[name] = did
        w(
            "INSERT OR IGNORE INTO districts (id,org_id,name) VALUES "
            f"({q(did)},{q(ORG_ID)},{q(name)});"
        )
    w("")

    # --- facilities / buildings / projects / documents / floors ------------
    marker_floor = {}  # v1 doc_id -> v2 floor id

    for p in projects:
        pname = p["name"]
        dname = (p["district"] or "").strip()
        did = districts.get(dname)

        fac_id = det_id("fac", "els911", pname)
        bld_id = det_id("bld", "els911", pname, "Main")
        proj_id = p["id"]  # keep the v1 project id

        w(f"-- {pname}")
        w(
            "INSERT OR IGNORE INTO facilities (id,district_id,org_id,name,type,address,zip,phone) VALUES "
            f"({q(fac_id)},{q(did)},{q(ORG_ID)},{q(pname)},{q('school')},"
            f"{q(p['address'])},{q(p['zip'])},{q(p['phone'])});"
        )

        docs = list(
            db.execute(
                "SELECT * FROM documents WHERE project_id = ? ORDER BY uploaded_at", (proj_id,)
            )
        )

        # Build the floor stack for this project.
        plan = FLOOR_PLAN.get(pname)
        if plan is None:
            plan = [("Main", None)] if docs else []

        w(
            "INSERT OR IGNORE INTO buildings (id,facility_id,name,floors) VALUES "
            f"({q(bld_id)},{q(fac_id)},{q('Main')},{max(1, len(plan))});"
        )
        w(
            "INSERT OR IGNORE INTO projects (id,building_id,name,status,progress,created_by,created_at) VALUES "
            f"({q(proj_id)},{q(bld_id)},{q(pname)},{q(map_status(p['status']))},"
            f"{q(p['progress'] or 0)},{q(p['created_by'] or fallback_user)},{q(p['created_at'])});"
        )

        for d in docs:
            w(
                "INSERT OR IGNORE INTO documents (id,project_id,filename,storage_key,size,page_count,"
                "doc_type,mime_type,version,status,uploaded_by,uploaded_at) VALUES "
                f"({q(d['id'])},{q(proj_id)},{q(d['filename'])},{q(d['storage_key'])},"
                f"{q(d['size'])},{q(d['page_count'] or 1)},{q('floorplan')},"
                f"{q(d['mime_type'] or 'application/pdf')},1,{q('active')},"
                f"{q(d['uploaded_by'] or fallback_user)},{q(d['uploaded_at'])});"
            )

        # Markers per document decide which version of a floor is current.
        marker_count = {
            d["id"]: db.execute(
                "SELECT COUNT(*) c FROM map_markers WHERE doc_id = ?", (d["id"],)
            ).fetchone()["c"]
            for d in docs
        }

        for order, (label, fragments) in enumerate(plan):
            floor_id = det_id("flr", "els911", pname, label)
            w(
                "INSERT OR IGNORE INTO floors (id,building_id,label,level,sort_order) VALUES "
                f"({q(floor_id)},{q(bld_id)},{q(label)},NULL,{order});"
            )

            if fragments is None:
                members = docs
            else:
                members = [d for d in docs if any(f in d["filename"] for f in fragments)]
            if not members:
                continue

            # The document holding the annotation work is the current plan.
            current = max(members, key=lambda d: (marker_count[d["id"]], d["uploaded_at"]))
            for vnum, d in enumerate(members, start=1):
                is_current = 1 if d["id"] == current["id"] else 0
                vid = det_id("fpv", "els911", pname, label, d["id"])
                note = None if is_current else "superseded by a later survey"
                w(
                    "INSERT OR IGNORE INTO floor_plan_versions "
                    "(id,floor_id,doc_id,page,version,is_current,note) VALUES "
                    f"({q(vid)},{q(floor_id)},{q(d['id'])},1,{vnum},{is_current},{q(note)});"
                )
                marker_floor[d["id"]] = floor_id
        w("")

    # --- annotations + markers --------------------------------------------
    w("-- annotations")
    for a in db.execute("SELECT * FROM annotations"):
        w(
            "INSERT OR IGNORE INTO annotations (id,document_id,page_number,type,nx,ny,nw,nh,points,"
            "color,text,created_by,created_at) VALUES "
            f"({q(a['id'])},{q(a['document_id'])},{q(a['page_number'] or 1)},{q(a['type'])},"
            f"{q(a['nx'])},{q(a['ny'])},{q(a['nw'])},{q(a['nh'])},{q(a['points'])},"
            f"{q(a['color'])},{q(a['text'])},{q(a['created_by'] or fallback_user)},{q(a['created_at'])});"
        )
    w("")

    w("-- map markers, now owned by a floor")
    for m in db.execute("SELECT * FROM map_markers"):
        floor_id = marker_floor.get(m["doc_id"])
        w(
            "INSERT OR IGNORE INTO map_markers (id,doc_id,page,type,label,label_pinned,nx,ny,"
            "label_nx,label_ny,points,extra_labels,created_by,created_at,floor_id) VALUES "
            f"({q(m['id'])},{q(m['doc_id'])},{q(m['page'] or 1)},{q(m['type'])},{q(m['label'])},"
            f"{q(m['label_pinned'] or 0)},{q(m['nx'])},{q(m['ny'])},{q(m['label_nx'])},"
            f"{q(m['label_ny'])},{q(m['points'])},{q(m['extra_labels'])},"
            f"{q(m['created_by'] or fallback_user)},{q(m['created_at'])},{q(floor_id)});"
        )
    w("")

    w("-- map crops")
    for c in db.execute("SELECT * FROM map_crops"):
        w(
            "INSERT OR IGNORE INTO map_crops (doc_id,page,nx,ny,nw,nh,label,print_order) VALUES "
            f"({q(c['doc_id'])},{q(c['page'])},{q(c['nx'])},{q(c['ny'])},{q(c['nw'])},"
            f"{q(c['nh'])},{q(c['label'])},{q(c['print_order'] or 0)});"
        )

    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
